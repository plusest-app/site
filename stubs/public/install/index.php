<?php

/**
 * ============================================================================
 *  Веб-установник бази нерухомості
 * ============================================================================
 *
 *  Відкрийте цю адресу в браузері після того, як розпакували архів на
 *  хостинг і налаштували вебсервер:
 *
 *      https://ваш-сайт/base/install/
 *
 *  Перший крок попросить ключ доступу. Установник запише його у файл
 *  plusestSite/data/installKey.txt — відкрийте цей файл тим самим FTP-клієнтом
 *  чи файловим менеджером, яким заливали архів, і скопіюйте ключ у форму. Так
 *  ніхто, крім вас, установником не скористається, навіть якщо вгадає адресу.
 *
 *  Цей каталог можна не видаляти після встановлення: щоб щось тут зробити,
 *  потрібен ключ із файлу, недоступного з вебу, а от перенастроїти базу даних
 *  чи розміри фотографій через форму значно зручніше, ніж правити config.php
 *  по FTP.
 *
 *  Уся робота відбувається у класі Plusest\Site\Installer\WebInstaller — цей
 *  файл лише знаходить автозавантажувач Composer і передає йому керування.
 * ============================================================================
 */

// --- Пошук автозавантажувача Composer ---------------------------------------
//  Каталог install лежить у public, тому до кореня заготовки — два рівні
//  вгору. Далі — варіанти встановлення через Composer, коли vendor/ лежить
//  вище за каталог plusestSite.
$plusestRoot = dirname(__DIR__, 2);

$plusestAutoload = null;

foreach ([
    $plusestRoot . '/vendor/autoload.php',
    dirname($plusestRoot) . '/vendor/autoload.php',
    dirname($plusestRoot, 2) . '/vendor/autoload.php',
] as $plusestCandidate) {
    if (is_file($plusestCandidate)) {
        $plusestAutoload = $plusestCandidate;

        break;
    }
}

if ($plusestAutoload === null) {
    http_response_code(500);

    exit(
        '<!doctype html><html lang="uk"><meta charset="utf-8">'
        . '<p>Не знайдено автозавантажувач Composer (каталог vendor). '
        . 'Перевірте, чи архів розпакувався повністю.</p>'
    );
}

require $plusestAutoload;

// Форма установника перевіряє підключення до бази й завантажує моделі даних
// з мережі — і те, і те буває неквапливим. Ліміт часу знімаємо, наскільки
// хостинг це дозволяє.
if (function_exists('set_time_limit')) {
    @set_time_limit(120);
}

$plusestInstaller = new Plusest\Site\Installer\WebInstaller($plusestRoot);
$plusestInstaller->run();
